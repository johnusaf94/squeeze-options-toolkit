def _clock_html(clock):
    marks = "".join(
        '<div class="mark {k}" style="left:{p:.2f}%"><div>{l}</div>'
        '<div>{d:%b %d}</div><div class="stem"></div></div>'.format(
            k=m["kind"], p=m["pct"] * 100, l=_esc(m["label"]), d=m["date"])
        for m in clock["marks"])
    exps = "".join(
        '<div class="exp {c}" style="left:{p:.2f}%"><div class="dot"></div>'
        '{d:%m-%d}<br>{n}d</div>'.format(
            c=("miss" if e["misses"] else ("cover" if e["covers"] else "")),
            p=e["pct"] * 100, d=e["date"], n=e["days"])
        for e in clock["expiries"])
    return ('<div class="clock"><div class="axis">'
            '<div class="today">TODAY {t:%b %d}</div>'
            '<div class="rail"></div>{m}{e}</div></div>').format(
        t=clock["today"], m=marks, e=exps)


def _items_html(items, cls):
    title = {"for": "The case for", "against": "The case against",
             "unknown": "Present but unweighted"}[cls]
    if not items:
        return ('<div class="col {c}"><p class="lab">{t}</p>'
                '<div class="item"><div class="d">Nothing recorded.</div>'
                '</div></div>').format(c=cls, t=title)
    rows = "".join(
        '<div class="item"><div class="k">{k}</div><div class="v">{v}</div>'
        '<div class="d">{d}</div></div>'.format(k=_esc(k), v=_esc(v), d=_esc(d))
        for k, v, d in items)
    return '<div class="col {c}"><p class="lab">{t}</p>{r}</div>'.format(
        c=cls, t=title, r=rows)


def _cfg():
    try:
        import trading_config
        return trading_config.load()
    except Exception:
        return {"capital": 0.0, "max_position_pct": 0.0}


def _structures_html(opt):
    st = (opt or {}).get("structures") or {}
    if not st:
        return ('<p class="sub">No structure survived the liquidity and cost '
                'filters. Outside market hours every bid is cleared, and a '
                'spread cannot be priced without a bid to sell into.</p>')
    rows = ""
    for k, r in sorted(st.items(), key=lambda kv: -(kv[1].get("kelly") or -9)):
        ev, kel = _f(r.get("ev")), _f(r.get("kelly"))
        sz = r.get("sizing") or {}
        n_ct = sz.get("contracts", 0)
        if n_ct >= 1:
            order = ('<span class="pos">{}×</span> = ${:,.0f} ({:.0%})'
                     .format(n_ct, sz["dollars"], sz["pct"]))
        else:
            order = ('<span class="neg">—</span> <span style="opacity:.7">{}'
                     '</span>'.format(_esc(sz.get("bound_by", "not sized"))))
        rows += ('<tr><td class="name">{k}</td><td class="name">{n}</td>'
                 '<td>{deb}</td><td>{pc}</td><td class="{ec}">{ev}</td>'
                 '<td class="{kc}">{kel}</td><td>{pw}</td>'
                 '<td class="name">{o}</td></tr>').format(
            k=_esc(k), n=_esc(r.get("name", "")), deb=_num(r.get("debit"), 2),
            pc="${:,.0f}".format(sz.get("per_contract", 0)),
            ec="pos" if (ev or 0) > 0 else "neg", ev=_pct(ev),
            kc="pos" if (kel or 0) > 0 else "neg", kel=_num(kel, 2),
            pw=_pct(r.get("p_profit")), o=order)
    return ('<div class="tbl"><table><thead><tr><th>family</th>'
            '<th>structure</th><th>debit</th><th>per contract</th><th>EV</th>'
            '<th>Kelly</th><th>P(win)</th><th>your order</th>'
            '</tr></thead><tbody>' + rows + '</tbody></table></div>')


def _falsifiers(case, opt):
    out = []
    lp = case["learned"]
    vp = lp.get("vol_premium") or {}
    ratio, im = _f(vp.get("ratio")), case.get("implied_move")
    if ratio and im:
        out.append("Implied move falls below <b>{:.1%}</b>, or your thesis "
                   "rises above it. Today the market charges {:.1%} for "
                   "movement these names have delivered {:.2f}× of."
                   .format(im * ratio, im, ratio))
    fam = case.get("family")
    vs = ((lp.get("verdicts") or {}).get("families") or {}).get(fam)
    if vs and vs["mean_10d"] <= -3.0:
        out.append("The verdict moves off <b>{}</b>. That family averages "
                   "{:+.1f}% over {} graded episodes; BUILDING has been the "
                   "only family with a positive mean."
                   .format(_esc(fam), vs["mean_10d"], vs["n"]))
    cal = lp.get("calibration") or {}
    if not cal.get("active"):
        out.append("The calibration model clears its gate (holdout AUC "
                   "≥0.55). Until it does there is no per-candidate "
                   "probability, and every number here is a base rate plus "
                   "your own scenario.")
    if not (opt or {}).get("structures"):
        out.append("A live session provides two-sided quotes so a spread can "
                   "be priced. A long call buys the volatility premium; a "
                   "spread sells part of it back.")
    out.append("A filled trade lands in the journal. With no closed trades "
               "there is no realized evidence that any of this prices "
               "correctly — only that it is internally consistent.")
    return "".join("<li>{}</li>".format(s) for s in out)


def render(ticker, case, clock, opt=None, out_path="", open_after=True):
    lp = case["learned"]
    cal = lp.get("calibration") or {}
    ps = lp.get("path_shape_event") or {}
    vcls = {"NO TRADE": "v-no", "TRADEABLE": "v-go",
            "WAIT": "v-wait"}.get(case["verdict"], "v-wait")
    spot = case["spot"]
    unknown_block = ""
    if case["unknown"]:
        unknown_block = ('<div class="ledger" style="margin-top:22px">'
                         + _items_html(case["unknown"], "unknown") + "</div>")

    doc = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{tk} Squeeze Thesis</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Archivo:wght@600;700&amp;family=JetBrains+Mono:wght@400;500&amp;family=Newsreader:opsz,wght@6..72,400;6..72,500&amp;display=swap">
<style>{css}</style></head><body><div class="wrap">

<header class="hero">
  <p class="lab">Squeeze thesis &middot; generated {now:%d %b %Y %H:%M}</p>
  <div class="tick"><h1>{tk}</h1><span class="px">{px}</span>
    <span class="px">{dv}</span></div>
  <div class="verdict {vcls}">{verdict}</div>
  <p class="why">{why}</p>
</header>

<section>
  <h2>The clock</h2>
  <p class="sub">Every date that matters on one axis. A green dot marks an
  expiry that covers the events; red misses at least one. An expiry can cover
  the close-out and still expire before earnings, and that gap is invisible on
  every other screen.</p>
  {clock}
</section>

<section>
  <div class="ledger">{forc}{against}</div>
  {unknown}
</section>

<section>
  <h2>The expression</h2>
  <p class="sub">Best structure of each family, all scored on one
  distribution, one forward, one crush assumption and full round-trip costs.
  <b>Your order</b> is quarter-Kelly against {cap}, capped at
  {maxpct} — structures whose single contract exceeds that ceiling are
  dropped entirely, because an idea you cannot buy is not a trade.</p>
  {structures}
</section>

<section>
  <h2>What would change this</h2>
  <p class="sub">The conditions under which the verdict flips. A verdict you
  cannot argue with is a verdict you cannot learn from.</p>
  <ul class="fals">{falsifiers}</ul>
</section>

<footer>
  <div>EVIDENCE BASE — calibration n={cn} ({cw}W/{cl}L) across {ceff}
  independent episodes after collapsing repeat scans of the same ticker;
  path shape from {pn} event-aligned episodes; volatility premium from
  {vn} episodes.</div>
  <div style="margin-top:10px">Quotes are delayed and may be prior-session.
  This page ranks structures and states a verdict under disclosed
  assumptions. It does not know your position size, your alternatives, or
  your risk tolerance, and it has never seen one of your fills.</div>
</footer>

</div></body></html>""".format(
        tk=_esc(ticker), css=CSS, now=datetime.now(),
        px=("$" + _num(spot, 2)) if spot else "",
        dv=_esc(case.get("deep_verdict", "")),
        vcls=vcls, verdict=_esc(case["verdict"]), why=_esc(case["why"]),
        clock=_clock_html(clock),
        forc=_items_html(case["for"], "for"),
        against=_items_html(case["against"], "against"),
        unknown=unknown_block,
        structures=_structures_html(opt),
        cap="${:,.0f}".format(_cfg()["capital"]),
        maxpct="{:.0%}".format(_cfg()["max_position_pct"]),
        falsifiers=_falsifiers(case, opt),
        cn=cal.get("n", 0), cw=cal.get("winners", 0), cl=cal.get("losers", 0),
        ceff=cal.get("effective_n", "?"), pn=ps.get("n_episodes", 0),
        vn=(lp.get("vol_premium") or {}).get("n", 0))

    os.makedirs(OUT_DIR, exist_ok=True)
    path = out_path or os.path.join(
        OUT_DIR, "{}_{:%Y%m%d}.html".format(ticker.upper(), date.today()))
    with open(path, "w", encoding="utf-8") as f:
        f.write(doc)
    if open_after:
        try:
            webbrowser.open("file:///" + path.replace("\\", "/"))
        except Exception:
            pass
    return path
