"""
thesis_render.py
================
Turns the assembled case from thesis_page into one readable page.

Kept separate from the analysis so the argument and its presentation can be
changed independently — and so a rendering bug can never be mistaken for a
change in the evidence.

DESIGN NOTES
------------
The page is a CASE FILE, not a dashboard, and it is built to be read top to
bottom: verdict, clock, ledger, expression, falsifiers. The FOR and AGAINST
columns are deliberately the same width and weight. On this universe the base
rate is 13% and implied volatility runs richer than realized, so most honest
verdicts are NO TRADE; a layout that made the bull case bigger than the bear
case would be arguing for a position the data does not support.

Colours come from the analyzer's own palette so the page reads as part of the
toolkit rather than a export from somewhere else. It commits to a single dark
theme on purpose — it is generated by a dark application and opened beside it.
"""

